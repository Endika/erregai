// Regenerates src/core/services.data.ts from OpenStreetMap via Overpass.
// Downloads server-side; this is what the CI cron job runs. Nothing here ever
// executes in a browser — the app ships the generated dataset and never calls
// Overpass at runtime.
//
// OSM data is ODbL: see the "Service area data" section of the README for the
// attribution this obliges us to carry.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { normalizeServiceAreas } from './lib/services-normalize.mjs'

const SRC = new URL('../../erregai-notes/service-sources/', import.meta.url)
const OUT = new URL('../src/core/services.data.ts', import.meta.url)

// The main instance answers roughly two requests in three; the mirrors cover
// the rest. Tried in order, and the whole run fails rather than writing a
// half-empty dataset.
const MIRRORS = [
  'https://overpass-api.de/api/interpreter',
  'https://overpass.private.coffee/api/interpreter',
  'https://overpass.kumi.systems/api/interpreter',
]

// Overpass answers 406 to requests with no User-Agent or a browser-shaped one:
// OSM services want a client they can identify and contact. Not optional.
const UA = 'erregai-dataset-builder/1.0 (+https://github.com/endika/erregai)'

// Scoped by country rather than by bounding box. A box wide enough to hold the
// Canaries also holds southern France, Portugal and Andorra: it returned 1400
// areas where Spain has 999, and French ones sorted to the top of the dataset.
const SPAIN = 'area["ISO3166-1"="ES"][admin_level=2]->.es;'

const AREAS_QUERY = `[out:json][timeout:280];
${SPAIN}
nwr["highway"="services"](area.es);
out tags center;`

const POIS_QUERY = `[out:json][timeout:280];
${SPAIN}
way["highway"="services"](area.es)->.sa;
.sa map_to_area -> .a;
(
  nwr["amenity"~"^(restaurant|fast_food|cafe|fuel|toilets)$"](area.a);
  nwr["shop"="convenience"](area.a);
);
out tags center;`

const ATTEMPTS = 3
const BACKOFF_MS = 20_000

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function overpass(query, localName) {
  for (let attempt = 0; attempt < ATTEMPTS; attempt++) {
    // Every mirror is shared, free infrastructure. Back off between rounds
    // rather than retrying immediately: a 429 means slow down, not try harder.
    if (attempt > 0) await sleep(BACKOFF_MS * attempt)
    for (const mirror of MIRRORS) {
      try {
        const res = await fetch(mirror, { method: 'POST', body: query, headers: { 'User-Agent': UA } })
        if (!res.ok) { console.warn(`${mirror}: HTTP ${res.status}`); continue }
        const text = await res.text()
        // Overpass reports overload as an HTML error page with a 200 status, so
        // a successful response is not enough — it has to actually be JSON.
        if (!text.trimStart().startsWith('{')) { console.warn(`${mirror}: non-JSON response (busy)`); continue }
        return JSON.parse(text).elements ?? []
      } catch (e) {
        console.warn(`${mirror}: ${e.message}`)
      }
    }
  }
  const local = new URL(localName, SRC)
  if (existsSync(local)) {
    console.warn(`all mirrors failed - using local ${localName}`)
    return JSON.parse(readFileSync(local, 'utf8')).elements ?? []
  }
  throw new Error(`no Overpass mirror answered for ${localName} and no local fallback`)
}

// Sequential on purpose: two heavy queries fired at once from one IP is what
// earns a 429 in the first place.
const areaElements = await overpass(AREAS_QUERY, 'areas.json')
const poiElements = await overpass(POIS_QUERY, 'pois.json')
console.log(`  areas: ${areaElements.length} elements, pois: ${poiElements.length} elements`)

const areas = normalizeServiceAreas(areaElements, poiElements)
if (areas.length === 0) {
  console.error('no service areas produced - aborting')
  process.exit(1)
}

const round = (n) => Math.round(n * 1e5) / 1e5
const field = (key, value) => (value === undefined ? '' : `${key}: ${JSON.stringify(value)}, `)
const body = areas
  .map(
    (a) =>
      `  { id: ${JSON.stringify(a.id)}, lat: ${round(a.lat)}, lon: ${round(a.lon)}, ` +
      field('name', a.name) +
      `services: ${JSON.stringify(a.services)}, ` +
      field('hours', a.hours) +
      `},`,
  )
  .join('\n')
const generatedOn = new Date().toISOString().slice(0, 10)
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-services.mjs - do not edit by hand.\n` +
    `import type { ServiceArea } from './services'\n\n` +
    `export const SERVICES_DATASET_DATE = '${generatedOn}'\n\n` +
    `export const SERVICE_AREAS: readonly ServiceArea[] = [\n${body}\n]\n`,
)
const withHours = areas.filter((a) => a.hours).length
console.log(`Wrote ${areas.length} service areas (${withHours} with opening hours, date ${generatedOn}).`)
